# 任務定義
# 欄位說明：
#   version          : 此任務定義的版本號（獨立於系統版本）
#   name             : 任務名稱
#   description      : 任務簡述（顯示於任務頁面 header）
#   week_range       : 對應課程週次
#   estimated_hours  : 預估完成時間
#   difficulty       : 難度標示
#   learning_goals   : 學習標的列表（用於 AI prompt context）
#   accountability_focus : 當責重點（用於 AI 評分 context）
#   role_description : 角色定位說明（顯示於任務說明區塊）
#
#   prompt_questions  : 提示問題，每題有唯一 id
#   checklist_items   : 自我檢核清單，每項有唯一 id
#                       optional=True 表示選做項目
#   reflection_questions : 當責反思題，每題有唯一 id
#   deliverables      : 任務產出，每項有唯一 id
#                       type: system_record | screenshot | file | reflection_report | optional_file
#                       accept_file: 是否接受檔案上傳
#                       accept_text: 是否接受文字輸入
#                       optional: 是否為選做
# =============================================================================

